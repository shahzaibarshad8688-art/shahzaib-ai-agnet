import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const WORKSPACE_DIR = path.resolve(__dirname, '../../../data/workspace');

export const docGeneratorTool = {
  name: 'doc_generator',
  label: 'Document & Report Generator',
  description: 'Generate structured markdown reports, research briefs, documentation, or HTML pages and save them to the agent workspace.',
  category: 'documents',
  requiresConfirmation: false,
  dangerLevel: 'safe',
  enabled: true,
  parameters: {
    type: 'object',
    properties: {
      title: {
        type: 'string',
        description: 'Document title'
      },
      format: {
        type: 'string',
        enum: ['markdown', 'html', 'json', 'text'],
        description: 'File format (default: markdown)'
      },
      content: {
        type: 'string',
        description: 'The body content or sections of the document'
      },
      filename: {
        type: 'string',
        description: 'Optional filename (e.g. "ai_research_report.md"). If not provided, generated from title.'
      },
      includeHeader: {
        type: 'boolean',
        description: 'Whether to include the official Shahzaib AI Agent header and timestamp metadata (default: true)'
      }
    },
    required: ['title', 'content']
  },

  async execute({ title, format = 'markdown', content, filename, includeHeader = true }) {
    await fs.mkdir(WORKSPACE_DIR, { recursive: true });

    let ext = '.md';
    if (format === 'html') ext = '.html';
    if (format === 'json') ext = '.json';
    if (format === 'text') ext = '.txt';

    const safeName = filename || (
      title.toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '')
        .slice(0, 45) + ext
    );

    const safePath = path.resolve(WORKSPACE_DIR, safeName);
    if (!safePath.startsWith(WORKSPACE_DIR)) {
      throw new Error('Access denied: Invalid filename.');
    }

    const timestamp = new Date().toLocaleString();
    let finalDoc = '';

    if (format === 'markdown') {
      finalDoc = includeHeader
        ? `# ${title}\n\n` +
          `> **Author / Principal**: SHAHZAIB ARSHAD KHAGGA  \n` +
          `> **Generated by**: Shahzaib AI Agent  \n` +
          `> **Date**: ${timestamp}  \n\n---\n\n` +
          `${content}\n\n---\n*Shahzaib AI Agent • Autonomous Intelligence Workstation*\n`
        : `# ${title}\n\n${content}\n`;
    } else if (format === 'html') {
      finalDoc = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(title)}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; line-height: 1.6; max-width: 860px; margin: 40px auto; padding: 0 20px; color: #1e293b; background: #f8fafc; }
    header { border-bottom: 2px solid #6366f1; padding-bottom: 16px; margin-bottom: 30px; }
    h1 { color: #0f172a; margin: 0 0 10px 0; }
    .meta { color: #64748b; font-size: 0.9rem; }
    pre { background: #0f172a; color: #f8fafc; padding: 16px; border-radius: 8px; overflow-x: auto; }
    footer { margin-top: 50px; padding-top: 20px; border-top: 1px solid #e2e8f0; font-size: 0.85rem; color: #94a3b8; }
  </style>
</head>
<body>
  <header>
    <h1>${escapeHtml(title)}</h1>
    <div class="meta">Created for <strong>SHAHZAIB ARSHAD KHAGGA</strong> by Shahzaib AI Agent • ${timestamp}</div>
  </header>
  <main>
    ${content}
  </main>
  <footer>Shahzaib AI Agent — Autonomous Workspace</footer>
</body>
</html>`;
    } else {
      finalDoc = content;
    }

    await fs.writeFile(safePath, finalDoc, 'utf-8');
    const wordCount = finalDoc.trim().split(/\s+/).length;

    return {
      status: 'success',
      filename: safeName,
      relativePath: safeName,
      bytes: Buffer.byteLength(finalDoc, 'utf8'),
      wordCount,
      format,
      preview: finalDoc.slice(0, 300) + (finalDoc.length > 300 ? '...' : '')
    };
  }
};

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export default docGeneratorTool;
